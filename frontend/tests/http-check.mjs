import assert from 'node:assert/strict'

const base = new URL(process.env.ATLAS_BASE_URL ?? 'http://127.0.0.1:3000')
assert.ok(['http:', 'https:'].includes(base.protocol))
const get = (path, headers = {}) => fetch(new URL(path, base), { headers, signal: AbortSignal.timeout(15_000) })
const home = await get('/')
assert.equal(home.status, 200)
assert.equal(home.headers.get('x-content-type-options'), 'nosniff')
assert.equal(home.headers.get('x-frame-options'), 'DENY')
assert.ok(home.headers.get('content-security-policy')?.includes("frame-ancestors 'none'"))
const html = await home.text()
const asset = /src="(\/assets\/[^" ]+\.js)"/.exec(html)?.[1]
assert.ok(asset, 'The production HTML must reference a versioned JavaScript asset')
const javascript = await get(asset)
assert.equal(javascript.status, 200)
assert.ok(javascript.headers.get('cache-control')?.includes('max-age=31536000'))
assert.equal(javascript.headers.get('x-content-type-options'), 'nosniff')
const geography = await get('/geodata/countries-110m.geojson')
assert.equal(geography.headers.get('content-encoding'), 'gzip')
assert.ok(geography.headers.get('content-type')?.includes('application/geo+json'))
assert.ok(geography.headers.get('cache-control')?.includes('max-age=86400'))
assert.ok((await geography.json()).features.length > 0)
const index = await get('/index.html')
assert.ok(index.headers.get('cache-control')?.includes('no-cache'))
const api = await get('/api/openapi')
assert.equal(api.status, 200)
assert.equal(api.headers.get('content-encoding'), 'gzip')
assert.equal((await api.json()).info.title, 'Atlas Global API')
assert.equal((await get('/healthz')).status, 200)
assert.equal((await get('/actuator/health')).status, 404)
assert.equal((await get('/api/actuator/health')).status, 404)
console.log('PASS security headers, compression, versioned asset caching, HTML revalidation and management isolation')

if (process.argv.includes('--rate-limit-check')) {
  assert.ok(['127.0.0.1', 'localhost', '[::1]'].includes(base.hostname), 'Burst verification is limited to a local test target')
  const responses = await Promise.all(Array.from({ length: 180 }, (_, index) =>
    get('/api/v1/sources?size=1', { 'X-Forwarded-For': `198.51.100.${index + 1}` })))
  const limited = responses.filter(response => response.status === 429)
  assert.ok(limited.length > 0, 'The local API burst must trigger the configured rate limit')
  assert.ok(responses.every(response => [200, 429].includes(response.status)))
  assert.ok(limited.every(response => response.headers.get('retry-after') === '1'))
  await Promise.all(responses.map(response => response.arrayBuffer()))
  await new Promise(resolve => setTimeout(resolve, 1500))
  assert.equal((await get('/api/v1/sources?size=1')).status, 200)
  console.log('PASS API burst returns 429 with Retry-After and recovers for later requests')
}
